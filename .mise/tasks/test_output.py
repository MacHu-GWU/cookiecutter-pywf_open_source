# -*- coding: utf-8 -*-

"""
L4: install and test the default-value project generated by test-template,
then build a wheel of every choice-coverage project (``output/choices/``),
so a choice value that breaks packaging (e.g. an invalid license expression)
is caught too.

Uses ``INSTALL_COMMAND`` / ``TEST_COMMAND`` from ``cctpl/pair.py`` directly, never mise (06-verification.md, "Secrets").
There is no uv.lock (it is excluded from the template), so dependencies
resolve fresh, as they will for a new user.

Exits 1 if installation, any test, or any build fails.
"""

import os
import json
import subprocess
from pathlib import Path

import cctpl


def _find_project() -> Path:
    cctpl.require_dir(cctpl.dir_output, "mise run test-template")
    projects = [
        p for p in cctpl.dir_output.iterdir() if p.is_dir() and p.name != "choices"
    ]
    if len(projects) != 1:
        raise cctpl.TaskError(
            f"expected one default-value project in {cctpl.dir_output}, found "
            f"{[p.name for p in projects]}. Run 'mise run test-template' first."
        )
    return projects[0]


def main() -> int:
    dir_project = _find_project()
    variables = json.loads(
        (cctpl.dir_template / "cookiecutter.json").read_text(encoding="utf-8")
    )
    if not cctpl.run_project_tests(dir_project, variables[cctpl.PYTHON_VERSION_VARIABLE]):
        return 1
    print(f"OK: generated project installs and its tests pass ({dir_project}).")

    env = {k: v for k, v in os.environ.items() if k != "VIRTUAL_ENV"}
    dir_choices = cctpl.dir_output / "choices"
    projects = sorted(dir_choices.glob("*/*/")) if dir_choices.is_dir() else []
    failed = []
    for dir_choice in projects:
        cmd = ["uv", "build", "--wheel", "--python", variables[cctpl.PYTHON_VERSION_VARIABLE]]
        print(f"$ {' '.join(cmd)}  (in {dir_choice})", flush=True)
        if subprocess.run(cmd, cwd=dir_choice, env=env).returncode != 0:
            failed.append(str(dir_choice.relative_to(cctpl.dir_output)))
    if failed:
        print(f"FAILED: wheel build failed for {', '.join(failed)}")
        return 1
    print(f"OK: {len(projects)} choice-coverage project(s) build a wheel.")
    return 0


if __name__ == "__main__":
    cctpl.run_task(main)
