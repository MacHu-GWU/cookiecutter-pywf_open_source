# -*- coding: utf-8 -*-

"""
L2: scan the project generated by test-template for unresolved cookiecutter
variable references, in file / directory names and file contents.
Exits 1 on any hit.

Plain ``{{`` / ``{%`` are not flagged: they may come from the seed itself.
"""

import re

import cctpl

# A cookiecutter variable reference inside a Jinja expression or statement.
_UNRESOLVED = re.compile(r"\{\{[^}]*cookiecutter\.|\{%[^%]*cookiecutter\.")


def main() -> int:
    cctpl.require_dir(cctpl.dir_output, "mise run test-template")
    problems: list[str] = []

    for path in sorted(cctpl.dir_output.rglob("*")):
        if _UNRESOLVED.search(path.name):
            problems.append(f"{path.relative_to(cctpl.dir_output)}: in path name")

    for rel, text in cctpl.iter_text_files(cctpl.dir_output):
        if not _UNRESOLVED.search(text):
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            if _UNRESOLVED.search(line):
                problems.append(f"{rel}:{lineno}: {line.strip()[:160]}")

    if problems:
        print("=== Unresolved cookiecutter variable references ===")
        for line in problems:
            print(f"  {line}")
        print()
        print(f"FAILED: {len(problems)} unresolved reference(s).")
        return 1
    print("OK: no unresolved cookiecutter variable references.")
    return 0


if __name__ == "__main__":
    cctpl.run_task(main)
